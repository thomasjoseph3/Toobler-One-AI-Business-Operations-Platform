/**
 * Whether a password is on the list of very common ones (ignoring capitals and punctuation), or is just one character
 * repeated ("aaaaaaaaaa"), or a run of digits going up or down ("123456789012").
 */
export function isCommonPassword(password: string): boolean {
  const simplified = simplify(password);
  if (COMMON_PASSWORDS.has(simplified)) return true;
  if (simplified.length > 0 && new Set(simplified).size === 1) return true;
  return isStraightDigitRun(simplified);
}

/** Whether the text is only digits that each go up by one or each go down by one ("45678901234"), wrapping 9 to 0. */
function isStraightDigitRun(text: string): boolean {
  if (text.length < 6 || !/^\d+$/.test(text)) return false;
  const steps = new Set<number>();
  for (let position = 1; position < text.length; position += 1) {
    steps.add((Number(text[position]) - Number(text[position - 1]) + 10) % 10);
  }
  return steps.size === 1 && (steps.has(1) || steps.has(9));
}
